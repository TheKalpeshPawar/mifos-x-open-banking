/**
 * Generic placeholder for a not-yet-implemented banking destination.
 *
 * Phase 2 of PLAN-kmp-greenfield-implementation registers all 44 screens as
 * type-safe routes with these empty composables so the nav host compiles end to
 * end. Each is replaced by its real `feature:{name}` screen in Phases 4–6.
 */
@Composable
internal fun PlaceholderScreen(
    title: String,
    modifier: Modifier = Modifier,
) {
    Box(
        modifier = modifier
            .fillMaxSize()
            .padding(24.dp),
        contentAlignment = Alignment.Center,
    ) {
        Column(
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.spacedBy(8.dp),
        ) {
            Text(
                text = title,
                style = MaterialTheme.typography.titleLarge,
                textAlign = TextAlign.Center,
            )
            Text(
                text = "Coming soon",
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                textAlign = TextAlign.Center,
            )
        }
    }
}
